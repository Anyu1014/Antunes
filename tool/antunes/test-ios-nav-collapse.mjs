// Contract for the current persistent glass shell. This does not test rendering.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const root=process.argv[2]||resolve(import.meta.dirname,'../..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const source=read('Sources/Kumone/Features/IOSMainWindow.swift');
const glass=read('Sources/Kumone/Features/GlassTabBar.swift');
const bottom=source.split('private func bottomBar(width:')[1].split('/// With four or more tabs')[0];
assert.equal((bottom.match(/\.nativeGlassCapsule\(\)/g)||[]).length,2,'each slot must have only one glass shell');
assert.match(bottom,/tabBar\(compact: true\)[\s\S]*?\.allowsHitTesting\(expanded\)\s+\.accessibilityHidden\(!expanded\)/);
assert.match(bottom,/avatarButton\(setExpanded: setExpanded\)[\s\S]*?\.allowsHitTesting\(!expanded\)\s+\.accessibilityHidden\(expanded\)/);
assert.match(bottom,/collapsedLyricButton\(setExpanded: setExpanded\)[\s\S]*?\.allowsHitTesting\(folded\)\s+\.accessibilityHidden\(!folded\)/);
assert(bottom.includes('.frame(width: navWidth, height: 64, alignment: .trailing)'));
assert(bottom.includes('.frame(width: lyricWidth, height: 64, alignment: .leading)'));
assert(bottom.includes('GlassEffectContainer(spacing: 12) { row }'));
assert(!bottom.includes('.drawingGroup()'));
assert(glass.includes('.highPriorityGesture(dragGesture(cellW: cellW, count: count))'));
assert(glass.includes('.glassEffect(.regular, in: Capsule(style: .continuous))'));
assert(glass.includes('.accessibilityIdentifier("section-tab-\\(item.tab.rawValue)")'));
assert(!/\bwindow\s*\.\s*backgroundColor\s*=/.test(source));
assert(source.includes('.accessibilityHidden(activeTab != tab)'));
console.log('PASS: one native shell per slot; only visible controls interactive; active tab accessible; no window recolor');
